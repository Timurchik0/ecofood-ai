// Тексты подсказок «как это считается» для дашборда. Берут пороги и веса из текущих настроек,
// поэтому после смены настроек на /admin подсказки показывают актуальные значения.

import { SHARES } from "./scoring";
import type { ScoringConfig } from "./scoring";

export type MetricHelp = Record<
  | "total" | "hot" | "warm" | "cold" | "volume" | "cost" | "avg" | "review" | "today"
  | "structure" | "activity" | "dynamics"
  | "colScore" | "colStatus" | "colVolume" | "colCost" | "colReadiness" | "colContact" | "colCrm",
  string
>;

const n = (v: number) => Math.round(v).toLocaleString("ru-RU");

function bandsText(bands: [number, number, number], weight: number, shares: number[], unit: string): string {
  const pts = shares.map((s) => Math.round(weight * s));
  return (
    `до ${n(bands[0])} ${unit} — ${pts[0]} б.; ` +
    `${n(bands[0])}–${n(bands[1])} — ${pts[1]} б.; ` +
    `${n(bands[1])}–${n(bands[2])} — ${pts[2]} б.; ` +
    `от ${n(bands[2])} — ${pts[3]} б.`
  );
}

export function metricHelp(cfg: ScoringConfig, includeDemo: boolean): MetricHelp {
  const w = cfg.weights;
  const sum = Object.values(w).reduce((a, b) => a + b, 0);
  const refusal = cfg.refusalCold
    ? "Ответ «Нет» на передачу отходов переработчику даёт COLD при любом балле."
    : "";
  const warmTo = `${cfg.hot - 1}`;

  return {
    total:
      `Все заявки предприятий в выборке (анкета в приложении и Google-форма)${includeDemo ? ", вместе с демо-данными" : "; демо-данные скрыты"}.\n` +
      "«Новых» — со статусом CRM «Новая». «С контактом» — оставили телефон, e-mail или @telegram.",
    hot:
      `Итоговый балл от ${n(cfg.hot)} до 100. Клиенты, которым стоит звонить первыми.\n` +
      `Доля = HOT ÷ все заявки.${refusal ? `\n${refusal}` : ""}`,
    warm:
      `Итоговый балл от ${n(cfg.warm)} до ${warmTo}. Перспективные клиенты: с ними работают после горячих.\n` +
      "Доля = WARM ÷ все заявки.",
    cold:
      `Итоговый балл ниже ${n(cfg.warm)}${cfg.refusalCold ? ", а также все, кто ответил «Нет» на передачу отходов переработчику" : ""}. Сейчас не приоритет.\n` +
      "Доля = COLD ÷ все заявки.",
    volume:
      "Сумма объёма отходов за месяц по всем заявкам (кг → т).\n" +
      "Каждый ответ приводится к кг в месяц: «1,5 тонны» → 1 500; диапазон «60–100» → середина; «50 кг в день» → ×30. Нераспознанные ответы в сумму не входят.",
    cost:
      "Сумма ежемесячных расходов на вывоз (сом) по всем заявкам.\n" +
      "Ответ приводится к сомам в месяц: «около 20 тыс.» → 20 000. Не указанные и нераспознанные суммы не входят.",
    avg: "Среднее арифметическое итоговых баллов (0–100) всех заявок в выборке.",
    review:
      "Заявки, которые нужно проверить вручную: число не распознано или выглядит подозрительно (например, «2» в поле «кг»), либо контакт неясен.\n" +
      "Причина указана в карточке заявки.",
    today:
      "До 3 заявок HOT с самым высоким баллом, у которых статус CRM «Новая» или «Контакт», то есть с ними ещё не работали.\n" +
      "Следующий шаг предлагает AI по ответам этой заявки.",
    structure:
      "Доли HOT / WARM / COLD среди всех заявок.\n" +
      "«Типы отходов» — сколько заявок отметили каждый тип. Можно выбрать несколько, поэтому сумма может быть больше числа заявок.",
    activity:
      "Число заявок по виду деятельности (до 8 крупнейших групп).\n" +
      "Цвет полосы: красный — HOT, жёлтый — WARM, серый — COLD; ширина сегмента пропорциональна доле в группе.",
    dynamics:
      "Заявки по дням за последние 14 дней (дата ответа в форме, время Бишкека).\n" +
      "Ниже — регионы: число заявок и доля HOT / WARM / COLD (до 5 крупнейших).",
    colScore:
      `Сумма баллов по шести критериям, приведённая к шкале 0–100${sum === 100 ? "" : ` (сумма весов сейчас ${n(sum)})`}:\n` +
      `объём ${n(w.volume)} · готовность передавать ${n(w.handover)} · регулярность вывоза ${n(w.frequency)} · интервью/пилот ${n(w.pilot)} · расходы ${n(w.cost)} · текущий способ ${n(w.handling)}.\n` +
      "Расчёт по каждой заявке — в её карточке.",
    colStatus:
      `HOT — от ${n(cfg.hot)} баллов; WARM — от ${n(cfg.warm)} до ${warmTo}; COLD — ниже ${n(cfg.warm)}.\n` +
      `${refusal ? `${refusal} ` : ""}Пороги меняются в настройках.`,
    colVolume:
      "Из ответа «примерный объём в месяц», в кг. Диапазон → середина, «в день / в неделю» → пересчёт в месяц. «Не распознан» — нужно уточнить.\n" +
      `Баллы (вес ${n(w.volume)}): ${bandsText(cfg.volumeBands, w.volume, SHARES.volume, "кг")}`,
    colCost:
      "Из ответа «сколько тратите на вывоз в месяц», в сомах.\n" +
      `Баллы (вес ${n(w.cost)}): ${bandsText(cfg.costBands, w.cost, SHARES.cost, "сом")}`,
    colReadiness:
      `Ответ на вопрос «Рассмотрели бы вы передачу отходов переработчику?» (вес ${n(w.handover)}):\n` +
      `«Да» — ${n(w.handover)} б.; «Зависит от условий» — ${Math.round(w.handover * SHARES.handoverMaybe)} б.; «Нет» — 0.`,
    colContact:
      "Телефон, e-mail или @telegram из анкеты. В открытой демо-версии скрыт (0555 *** *56), полностью виден администратору.\n" +
      `Готовность к интервью/пилоту даёт баллы (вес ${n(w.pilot)}): «Да» — ${n(w.pilot)}, «Возможно» — ${Math.round(w.pilot * SHARES.pilotMaybe)}, «Нет» — 0.`,
    colCrm:
      "Статус работы менеджера с заявкой: Новая → Контакт → Интервью → Пилот → Закрыта (или Отказ). Меняется в карточке заявки.",
  };
}
